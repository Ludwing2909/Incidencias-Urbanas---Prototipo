import {test,expect} from '@playwright/test'
test('formulario → API persistente → seguimiento → revisión → historial',async({page})=>{
  await page.goto('/registrar')
  await page.getByLabel('¿Qué ocurre?').fill('Hay bolsas de basura acumuladas junto a la vía pública.')
  await page.getByRole('button',{name:'Registrar y obtener código'}).click()
  await expect(page.getByRole('heading',{name:'Incidencia registrada'})).toBeVisible()
  const code=await page.locator('.code').innerText()
  const secret=await page.getByLabel('Secreto de seguimiento · guárdalo ahora').inputValue()
  await page.getByRole('link',{name:'Consultar el seguimiento',exact:true}).click()
  await page.getByLabel('Código de incidencia').fill(code)
  await page.getByLabel('Secreto de seguimiento',{exact:true}).fill(secret)
  await page.getByRole('button',{name:'Consultar estado'}).click()
  await expect(page.getByRole('heading',{name:code,exact:true})).toBeVisible()
  await page.goto('/personal')
  await page.getByLabel('Usuario',{exact:true}).fill('test-admin')
  await page.getByLabel('Contraseña',{exact:true}).fill('Test-password-123!')
  await page.getByRole('button',{name:'Iniciar sesión'}).click()
  await expect(page.getByRole('heading',{name:'Resumen de incidencias'})).toBeVisible()
  await page.getByRole('link',{name:'Bandeja',exact:true}).click()
  await page.getByLabel('Código',{exact:true}).fill(code)
  await page.getByRole('button',{name:'Buscar',exact:true}).click()
  await page.getByRole('row').filter({hasText:code}).getByRole('link',{name:'Revisar →',exact:true}).click()
  await page.getByLabel('Tema revisado').selectOption('C1')
  await page.getByLabel('Destino revisado').fill('Área revisada para demostración')
  await page.getByLabel('Motivo u observaciones').fill('Confirmación temática de ejercicio académico, sin envío real.')
  await page.getByRole('button',{name:'Guardar revisión humana'}).click()
  await expect(page.getByText('Actuación registrada en el historial.')).toBeVisible()
  await expect(page.locator('.timeline').getByText('Revisado',{exact:true})).toBeVisible()
  await expect(page.getByText('Predicción original',{exact:true})).toBeVisible()
  await page.goto('/seguimiento')
  await page.getByLabel('Código de incidencia').fill(code)
  await page.getByLabel('Secreto de seguimiento',{exact:true}).fill(secret)
  await page.getByRole('button',{name:'Consultar estado'}).click()
  await expect(page.locator('.badge')).toHaveText('Revisado')
})
test('vacío, secreto erróneo y diseño móvil',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/registrar')
  await expect(page.getByRole('button',{name:'Registrar y obtener código'})).toBeDisabled()
  await page.goto('/seguimiento')
  await page.getByLabel('Código de incidencia').fill('REC-2026-999999')
  await page.getByLabel('Secreto de seguimiento',{exact:true}).fill('incorrect-secret-12345678')
  await page.getByRole('button',{name:'Consultar estado'}).click()
  await expect(page.getByRole('alert')).toContainText('Código o secreto de consulta inválidos')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})

test('fuente externa estructurada: conteos reales, exclusión y filtros',async({page})=>{
  await page.goto('/personal')
  await page.getByLabel('Usuario',{exact:true}).fill('test-admin')
  await page.getByLabel('Contraseña',{exact:true}).fill('Test-password-123!')
  await page.getByRole('button',{name:'Iniciar sesión'}).click()
  await page.getByRole('link',{name:'Fuentes de datos',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Fuentes de datos',exact:true})).toBeVisible()
  await expect(page.getByText('Esta fuente no contiene descripciones libres.',{exact:true})).toBeVisible()
  await expect(page.locator('.stats article').filter({hasText:'Textos extraídos para entrenamiento'}).locator('strong')).toHaveText('0')
  await expect(page.locator('.stats article').filter({hasText:'Registros históricos'}).locator('strong')).toHaveText(/202[.,\s]296/)
  await page.getByLabel('Buscar tema original').fill('Jardines. Limpieza')
  await page.getByLabel('Estado de correspondencia').selectOption('ambiguo')
  await expect(page.getByRole('cell',{name:'Jardines. Limpieza',exact:true})).toBeVisible()
  await expect(page.getByRole('cell',{name:'Sin asignación',exact:true})).toBeVisible()
})

test('acceso directo sin sesión vuelve a fuentes después de autenticarse',async({page})=>{
  await page.goto('/admin/fuentes')
  await expect(page).toHaveURL(/\/personal$/)
  await expect(page.getByRole('heading',{name:'Acceso del personal'})).toBeVisible()
  await expect(page.getByRole('status')).toContainText('Después volverás a la página solicitada')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('Usuario',{exact:true}).fill('test-admin')
  await page.getByLabel('Contraseña',{exact:true}).fill('Test-password-123!')
  await page.getByRole('button',{name:'Iniciar sesión'}).click()
  await expect(page).toHaveURL(/\/admin\/fuentes$/)
  await expect(page.getByRole('heading',{name:'Fuentes de datos',exact:true})).toBeVisible()
})

test('un fallo de servicio permite reintentar sin confundirse con sesión ausente',async({page})=>{
  await page.route('**/api/v1/auth/me',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Servicio temporalmente no disponible'})}))
  await page.goto('/admin/fuentes')
  await expect(page.getByRole('alert')).toContainText('Servicio temporalmente no disponible')
  await expect(page.getByRole('button',{name:'Reintentar'})).toBeVisible()
  await expect(page).toHaveURL(/\/admin\/fuentes$/)
})
